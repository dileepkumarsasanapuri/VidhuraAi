    public List<StructuredPolicy> getAllCatalogPolicies() {
        java.util.Map<String, StructuredPolicy> map = new java.util.LinkedHashMap<>();
        for (StructuredPolicy p : getAuthenticAcquiredCatalog()) {
            map.put(p.getPolicyCode(), p);
        }
        for (StructuredPolicy p : getSeedCatalog()) {
            map.putIfAbsent(p.getPolicyCode(), p);
        }
        return new java.util.ArrayList<>(map.values());
    }

