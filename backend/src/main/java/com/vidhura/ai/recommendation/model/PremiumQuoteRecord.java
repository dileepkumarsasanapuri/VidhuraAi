package com.vidhura.ai.recommendation.model;

import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.Data;
import lombok.NoArgsConstructor;
import org.springframework.data.annotation.Id;
import org.springframework.data.mongodb.core.index.CompoundIndex;
import org.springframework.data.mongodb.core.index.CompoundIndexes;
import org.springframework.data.mongodb.core.index.Indexed;
import org.springframework.data.mongodb.core.mapping.Document;

import java.math.BigDecimal;
import java.time.Instant;

/**
 * MongoDB document representing an authentic or modelled premium quote.
 *
 * Strict Provenance Rule:
 * Differentiates between authentic quotes retrieved from official insurer portals / APIs
 * (with verified quoteReferenceNumber and sourceDocumentHash) versus actuarial model estimates.
 */
@Data
@Builder
@NoArgsConstructor
@AllArgsConstructor
@Document(collection = "premium_quotes")
@CompoundIndexes({
        @CompoundIndex(name = "policy_age_si_idx", def = "{'policyCode': 1, 'age': 1, 'sumInsured': 1}"),
        @CompoundIndex(name = "policy_age_si_zone_idx", def = "{'policyCode': 1, 'age': 1, 'sumInsured': 1, 'zone': 1}")
})
public class PremiumQuoteRecord {

    @Id
    private String id;

    @Indexed(unique = true)
    private String quoteId;

    @Indexed
    private String policyCode;

    private String uinRevision;

    @Indexed
    private String insurerCode;

    @Indexed
    private BigDecimal sumInsured;

    @Indexed
    private int age;

    private String pinCode;

    @Indexed
    private String zone;

    /**
     * Family construct: INDIVIDUAL, FLOATER_2A, FLOATER_2A_1C, FLOATER_2A_2C, PARENTS_2A
     */
    @Builder.Default
    private String familyConstruct = "INDIVIDUAL";

    @Builder.Default
    private BigDecimal deductible = BigDecimal.ZERO;

    private String roomCategory;

    /**
     * Final payable annual premium inclusive of 18% GST
     */
    private BigDecimal quotedAnnualPremium;

    /**
     * Net base premium before tax
     */
    private BigDecimal quotedBasePremium;

    /**
     * Goods & Services Tax (18% for Indian health insurance)
     */
    private BigDecimal quotedGst;

    /**
     * Channel from which quote was generated:
     * OFFICIAL_PORTAL, AGGREGATOR_API, DIRECT_FILING, ESTIMATED_ACTUARIAL_MODEL, SYNTHETIC_BENCHMARK
     */
    @Indexed
    private String quotingChannel;

    @Builder.Default
    private Instant quoteTimestamp = Instant.now();

    /**
     * Unique quote or proposal reference ID generated by insurer quoting portal
     */
    @Indexed
    private String quoteReferenceNumber;

    private String sourceUrl;

    /**
     * Cryptographic SHA-256 hash of the quotation response or prospectus sheet
     */
    @Indexed
    private String sourceDocumentHash;

    /**
     * Quotes in India expire after 15-30 days due to age progression or rate revisions
     */
    private Instant expiryTimestamp;

    @Builder.Default
    private boolean stale = false;

    /**
     * Verification status:
     * VERIFIED_AUTHENTIC_QUOTE: Verified direct quote with active insurer reference
     * ESTIMATED_ACTUARIAL_MODEL: Calculated via age-band grid & morbidity curves (clearly badged as non-binding)
     * UNVERIFIED: Pending checksum/channel verification
     */
    @Indexed
    @Builder.Default
    private String verificationStatus = "ESTIMATED_ACTUARIAL_MODEL";

    private String rawQuotePayload;
}
